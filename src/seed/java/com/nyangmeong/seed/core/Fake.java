    /** 문장 n개를 이은 본문 */
    public static String paragraph(Seed s, int minSentences, int maxSentences) {
        StringBuilder sb = new StringBuilder();
        int n = s.between(minSentences, maxSentences);
        for (int i = 0; i < n; i++) {
            if (i > 0) {
                sb.append(' ');
            }
            sb.append(s.pick(SENTENCES));
        }
        return sb.toString();
    }

    public static String personName(Seed s) {
        return s.pick(SURNAMES) + s.pick(GIVEN);
    }

